CREATE TABLE orcamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_cliente VARCHAR(100) NOT NULL,
    telefone VARCHAR(11) NOT NULL,
    data_entrega DATE NOT NULL,
    horario_entrega TIME NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ABERTO',
    observacoes VARCHAR(1000),
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP NOT NULL
);

CREATE TABLE servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orcamento_id BIGINT NOT NULL REFERENCES orcamento (id) ON DELETE CASCADE,
    descricao VARCHAR(200) NOT NULL
);

CREATE TABLE peca (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orcamento_id BIGINT NOT NULL REFERENCES orcamento (id) ON DELETE CASCADE,
    nome_peca VARCHAR(150) NOT NULL,
    quantidade INT NOT NULL CHECK (quantidade >= 1)
);

CREATE INDEX idx_orcamento_data_entrega ON orcamento (data_entrega);
CREATE INDEX idx_orcamento_telefone ON orcamento (telefone);
CREATE INDEX idx_servico_orcamento ON servico (orcamento_id);
CREATE INDEX idx_peca_orcamento ON peca (orcamento_id);
